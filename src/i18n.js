const DICTS = { en: EN, ru: RU };

/** Translate a key. Arrays are returned as-is (for lists like spinner verbs). */
export function t(key, params = {}) {
  const v = DICTS[lang()][key] ?? EN[key];
  if (v === undefined) return key;
  if (typeof v === 'function') return v(params);
  if (Array.isArray(v)) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

export const fmtTokens = (n) => (n >= 1000 ? `${(n / 1000).toFixed(1)}k` : String(n));

export function timeAgo(ms) {
  const s = Math.floor((Date.now() - ms) / 1000);
  if (s < 60) return t('time.justNow');
  const m = Math.floor(s / 60);
  if (m < 60) return t('time.minutes', { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t('time.hours', { n: h });
  return t('time.days', { n: Math.floor(h / 24) });
}

/** Translate a deferred message: plain string, or { key, ...params } stored by tools. */
export function tm(msg) {
  if (msg && typeof msg === 'object' && msg.key) return t(msg.key, msg);
  return msg ?? '';
}

/** Translated label for an enum value (falls back to the raw value). */
export function tv(value) {
  const key = `value.${value}`;
  const v = DICTS[lang()][key] ?? EN[key];
  return typeof v === 'string' ? v : String(value);
}
